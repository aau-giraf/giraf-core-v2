enum UserType
{
    Citizen,
    NonCitizen
}

// Record to store DB user object and its unencrypted password.
internal record SeededUser(User User, string PlainPassword);
// Record of optional parameters used in user seeding.
// If UserOptions is not supplied, a random password will be generated and user type will default to citizen.
// class id should be a positive integer to be valid, else it will be random.
internal record UserOptions(string Password = "", int ClassId = -9999, UserType Type = UserType.Citizen);

internal class UserSeeder : ISeeder<User, SeededUser, UserOptions>
{
    // Create a random user and add it to mock database.
    public async Task<SeededUser> SeedAsync(AppDbContext db, int seed, UserOptions? userOptions = null)
    {
        var user = Create(seed, userOptions);

        // add user to db
        db.Users.Add(user.User);
        await db.SaveChangesAsync();

        return user;
    }

    // Create x random users and add them to mock database.
    public async Task<List<SeededUser>> SeedManyAsync(AppDbContext db, int seed, int count, List<UserOptions?>? userOptions = null)
    {
        var users = CreateMany(seed, count, userOptions);

        // add all User classes to db.
        db.Users.AddRange(users.Select(x => x.User));
        await db.SaveChangesAsync();

        return users;
    }

    // Generate a random user.
    public SeededUser Create(int seed, UserOptions? userOptions = null)
    {
        UserOptions opt = OptionHandler(seed, userOptions);

        var user = CreateFaker(seed, opt).Generate();

        return new SeededUser(user, opt.Password);
    }

    // Create x random users.
    public List<SeededUser> CreateMany(
        int seed,
        int count,
        List<UserOptions?>? userOptions = null)
    {
        var users = new List<SeededUser>();
        // Some int used to offset seed.
        int increment = 10;

        if (userOptions is not null)
        {
            if (count < userOptions.Count)
            {
                throw new ArgumentException("The options list cannot exceed the size of count! " + nameof(userOptions));
            }

            // Create users with supplied options.
            for (int i = 0; i < userOptions.Count; i++)
            {
                // Offset seed to differ users.
                int offset = seed + (i * increment);
                // Create random user based on supplied options.
                UserOptions opt = OptionHandler(offset, userOptions[i]);
                User user = CreateFaker(offset, opt).Generate();

                users.Add(new SeededUser(user, opt.Password));
            }
        }

        // Create users remaining users with random options.
        for (int i = 0; i < count - (userOptions?.Count ?? 0); i++)
        {
            // Offset seed to differ users and account for ones generated by options.
            int offset = seed + ((i + (userOptions?.Count ?? 0)) * increment);
            // Create random options.
            UserOptions opt = OptionHandler(offset, null);
            User user = CreateFaker(offset, opt).Generate();

            users.Add(new SeededUser(user, opt.Password));
        }

        return users;
    }

    // Create a random test user using bogus.
    public Faker<User> CreateFaker(int seed, UserOptions userOptions)
    {
        return new Faker<User>()
            .UseSeed(seed)
            .CustomInstantiator(f =>
            {
                var username = f.Internet.UserName();
                var firstName = f.Name.FirstName();
                var lastName = f.Name.LastName();
                var password = BCrypt.Net.BCrypt.HashPassword(
                    userOptions.Password, 12);

                User user = userOptions.Type switch
                {
                    UserType.Citizen => new Citizen
                    {
                        Username = username,
                        FirstName = firstName,
                        LastName = lastName,
                        Password = password,
                        ClassId = userOptions.ClassId
                    },

                    UserType.NonCitizen => new NonCitizen
                    {
                        Username = username,
                        FirstName = firstName,
                        LastName = lastName,
                        Password = password,
                        Email = f.Internet.Email()
                    },

                    _ => throw new ArgumentOutOfRangeException(
                        nameof(userOptions.Type))
                };

                return user;
            });
    }

    // Makes the options always usable by create faker
    private UserOptions OptionHandler(int seed, UserOptions? userOptions)
    {
        const int minLength = 8;

        // Check a password exists and use if length requirement is fulfilled, else generate a random one.
        string password = userOptions?.Password is { Length: >= minLength }
            ? userOptions.Password
            : new Faker<string>()
                .UseSeed(seed)
                .CustomInstantiator(f => f.Internet.Password())
                .Generate();

        UserType type = userOptions?.Type ?? UserType.Citizen;

        int classId = userOptions?.ClassId is not null and > 0 ? userOptions.ClassId : new Random(seed).Next(1, Int32.MaxValue);

        return new(password, classId, type);
    }
}