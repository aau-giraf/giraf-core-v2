// Options for creating org, if not supplied a random name is generated.
internal record OrgOptions(string Name = "");

internal class OrganizationSeeder : ISeeder<Organization, Organization, OrgOptions>
{

    // Create a random organization and add it to mock database.
    public async Task<Organization> SeedAsync(AppDbContext db, int seed, OrgOptions? opt = null)
    {
        var organization = Create(seed, opt);

        db.Organizations.Add(organization);
        await db.SaveChangesAsync();

        return organization;
    }

    // Create x random organizations and add them to mock database.
    public async Task<List<Organization>> SeedManyAsync(AppDbContext db, int seed, int count, List<OrgOptions?>? opt = null)
    {
        var organizations = CreateMany(seed, count, opt);

        db.Organizations.AddRange(organizations);
        await db.SaveChangesAsync();

        return organizations;
    }

    // Generate a random organization.
    public Organization Create(int seed, OrgOptions? opt = null)
    {
        return CreateFaker(seed, opt).Generate();
    }

    // Create x random organizations.
    public List<Organization> CreateMany(int seed, int count, List<OrgOptions?>? opt = null)
    {
        List<Organization> orgs = [];
        // some int used to offset seed.
        int increment = 10;

        if (opt is not null)
        {
            if (count < opt.Count)
            {
                throw new ArgumentException("The options list cannot exceed the size of count! " + nameof(opt));
            }

            // Create users with supplied options
            for (int i = 0; i < opt.Count; i++)
            {
                // Offset seed to differ users.
                int offset = seed + (i * increment);
                // Create random user role based on supplied options.
                orgs.Add(CreateFaker(offset, opt[i]).Generate());
            }
        }

        for (int i = 0; i < count - (opt?.Count ?? 0); i++)
        {
            // Offset seed to differ users and account for ones generated by options.
            int offset = seed + ((i + (opt?.Count ?? 0)) * increment);
            // Create user roles with random options.
            orgs.Add(CreateFaker(offset, null).Generate());
        }

        return orgs;
    }

    // Create a random test organization using bogus.
    public Faker<Organization> CreateFaker(int seed, OrgOptions? opt = null)
    {
        return new Faker<Organization>()
            .UseSeed(seed)
            .RuleFor(o => o.Name, f => opt is not null && !String.IsNullOrEmpty(opt.Name) ? opt.Name : f.Name.FirstName());
    }
}