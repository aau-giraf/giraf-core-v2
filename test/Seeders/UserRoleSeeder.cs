// Record of optional parameters. Non-positive numbers result in random postive integer.
internal record UserRoleOptions(int OrgId = -9999, int NonCitizenId = -9999);

internal class UserRoleSeeder : ISeeder<UserRole, UserRole, UserRoleOptions>
{

    // Create a random UserRole and add it to mock database.
    public async Task<UserRole> SeedAsync(AppDbContext db, int seed, UserRoleOptions? opt = null)
    {
        var userRole = Create(seed, opt);

        db.UserRoles.Add(userRole);
        await db.SaveChangesAsync();

        return userRole;
    }

    // Create x random UserRole and add them to mock database.
    public async Task<List<UserRole>> SeedManyAsync(AppDbContext db, int seed, int count, List<UserRoleOptions?>? opt = null)
    {
        var userRoles = CreateMany(seed, count, opt);

        db.UserRoles.AddRange(userRoles);
        await db.SaveChangesAsync();

        return userRoles;
    }

    // Generate a random userRole.
    public UserRole Create(int seed, UserRoleOptions? opt = null)
    {
        return CreateFaker(seed, opt).Generate();
    }

    // Create x random userRoles.
    public List<UserRole> CreateMany(int seed, int count, List<UserRoleOptions?>? opt)
    {

        List<UserRole> userRoles = [];
        // some int used to offset seed.
        int increment = 10;

        if (opt is not null)
        {
            if (count < opt.Count)
            {
                throw new ArgumentException("The options list cannot exceed the size of count! " + nameof(opt));
            }

            // Create users with supplied options
            for (int i = 0; i < opt.Count; i++)
            {
                // Offset seed to differ users.
                int offset = seed + (i * increment);
                // Create random user role based on supplied options.
                userRoles.Add(CreateFaker(offset, opt[i]).Generate());
            }
        }

        for (int i = 0; i < count - (opt?.Count ?? 0); i++)
        {
            // Offset seed to differ users and account for ones generated by options.
            int offset = seed + ((i + (opt?.Count ?? 0)) * increment);
            // Create user roles with random options.
            userRoles.Add(CreateFaker(offset, null).Generate());
        }

        return userRoles;
    }

    // Create a random test userRole using bogus.
    public Faker<UserRole> CreateFaker(int seed, UserRoleOptions? opt)
    {
        return new Faker<UserRole>()
            .UseSeed(seed)
            .RuleFor(ur => ur.NonCitizenId, f => opt is not null && opt.NonCitizenId > 0 ? opt.NonCitizenId : f.Random.Int(1, Int32.MaxValue))
            .RuleFor(ur => ur.OrganizationId, f => opt is not null && opt.OrgId > 0 ? opt.OrgId : f.Random.Int(1, Int32.MaxValue))
            .RuleFor(ur => ur.Role, f => f.PickRandom<RoleType>());
    }
}