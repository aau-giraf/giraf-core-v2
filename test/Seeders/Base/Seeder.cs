// Common seeder for general test seeders.
// TEntity -> database model to seed. (ex: UserRole model used in the database)
// TOption -> record containing all test specific parameters. (ex: UserRole seeding can optionally be supplied with a Citizen or NonCitizen ID)
// To add further options to an existing non-abstract seeder, simply expand the related record and make sure to account for possible cases (ex: something is null etc.) in CreateFaker()
internal abstract class Seeder<TEntity, TOptions> where TEntity : class
{
    // Create a random TEntity or use supplied options and add it to mock database.
    public abstract Task<TEntity> SeedAsync(AppDbContext db, int seed, TOptions options);

    // Create x random TEntity or use supplied options and add it to mock database.
    public abstract Task<List<TEntity>> SeedManyAsync(
        AppDbContext db,
        int seed,
        int count,
        List<TOptions> options
    );

    // Generate a TEntity.
    public TEntity Create(int seed, TOptions? options)
    {
        return CreateFaker(seed, options).Generate();
    }


    // Generate x TEntity based on options or randomly
    public List<TEntity> CreateMany(int seed, int count, List<TOptions>? options = null)
    {
        List<TEntity> list = [];
        // some int used to offset seed.
        int increment = 10;

        if (options is not null)
        {
            if (count < options.Count)
            {
                throw new ArgumentException("The options list cannot exceed the size of count! " + nameof(options));
            }

            // Create with supplied options
            for (int i = 0; i < options.Count; i++)
            {
                // Offset seed to differ entities.
                int offset = seed + (i * increment);
                // Create random entity based on supplied options.
                list.Add(CreateFaker(offset, options[i]).Generate());
            }
        }

        for (int i = 0; i < count - (options?.Count ?? 0); i++)
        {
            // Offset seed to differ entities and account for ones already generated by supplied options.
            int offset = seed + ((i + (options?.Count ?? 0)) * increment);
            // Create entitiy with random options.
            list.Add(CreateFaker(offset, default).Generate());
        }

        return list;
    }

    // Create a bogus faker with random content or based on optios.
    public abstract Faker<TEntity> CreateFaker(int seed, TOptions? options);
}