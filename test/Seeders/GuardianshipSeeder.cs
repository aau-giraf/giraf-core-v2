// Record of optional parameters. Non-positive numbers result in random postive integer.
internal record GuardianshipOptions(int CitizenId = -9999, int NonCitizenId = -9999);

internal class GuardianshipSeeder : ISeeder<Guardianship, Guardianship, GuardianshipOptions>
{

    // Create a random Guardianship and add it to mock database.
    public async Task<Guardianship> SeedAsync(AppDbContext db, int seed, GuardianshipOptions? opt = null)
    {
        var guardianship = Create(seed, opt);

        db.Guardianships.Add(guardianship);
        await db.SaveChangesAsync();

        return guardianship;
    }

    // Create x random Guardianship and add them to mock database.
    public async Task<List<Guardianship>> SeedManyAsync(AppDbContext db, int seed, int count, List<GuardianshipOptions?>? opt = null)
    {
        var guardianships = CreateMany(seed, count, opt);

        db.Guardianships.AddRange(guardianships);
        await db.SaveChangesAsync();

        return guardianships;
    }

    // Generate a random Guardianship.
    public Guardianship Create(int seed, GuardianshipOptions? opt = null)
    {
        return CreateFaker(seed, opt).Generate();
    }

    // Create x random Guardianships
    public List<Guardianship> CreateMany(int seed, int count, List<GuardianshipOptions?>? opt = null)
    {
        List<Guardianship> guardianships = [];
        // some int used to offset seed.
        int increment = 10;

        if (opt is not null)
        {
            if (count < opt.Count)
            {
                throw new ArgumentException("The options list cannot exceed the size of count! " + nameof(opt));
            }

            // Create guardianships with supplied options
            for (int i = 0; i < opt.Count; i++)
            {
                // Offset seed to differ guardianships.
                int offset = seed + (i * increment);
                // Create guardianship based on supplied options.
                guardianships.Add(CreateFaker(offset, opt[i]).Generate());
            }
        }

        for (int i = 0; i < count - (opt?.Count ?? 0); i++)
        {
            // Offset seed to differ guardianships and account for ones generated by options.
            int offset = seed + ((i + (opt?.Count ?? 0)) * increment);
            // Create guardianships random options.
            guardianships.Add(CreateFaker(offset, null).Generate());
        }

        return guardianships;
    }

    // Create a random test Guardianship using bogus.
    public Faker<Guardianship> CreateFaker(int seed, GuardianshipOptions? opt = null)
    {
        return new Faker<Guardianship>()
            .UseSeed(seed)
            .RuleFor(gs => gs.CitizenId, f => opt is not null && opt.CitizenId > 0 ? opt.CitizenId : f.Random.Int(1, Int32.MaxValue))
            .RuleFor(gs => gs.GuardianId, f => opt is not null && opt.NonCitizenId > 0 ? opt.NonCitizenId : f.Random.Int(1, Int32.MaxValue));
    }
}